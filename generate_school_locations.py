output = {}
missing = []

for school in snap_schools:
    if school in MANUAL_COORDS:
        lat, lng, city, state = MANUAL_COORDS[school]
        output[school] = {"lat": round(lat, 5), "lng": round(lng, 5),
                          "city": city, "state": state}
        continue

    # Resolve location string
    city, state, loc_str = None, None, None
    if school in school_to_loc:
        city, state, loc_str = school_to_loc[school]
    else:
        canon = alias_map.get(school)
        if canon and canon in school_to_loc:
            city, state, loc_str = school_to_loc[canon]

    if loc_str and loc_str in CITY_COORDS:
        lat, lng = CITY_COORDS[loc_str]
        output[school] = {"lat": round(lat, 5), "lng": round(lng, 5),
                          "city": city or "", "state": state or ""}
    else:
        missing.append((school, loc_str))

