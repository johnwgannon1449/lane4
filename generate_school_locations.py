# ── Load school list + location strings from main.py ──────────────────────────

content = open("main.py", encoding="utf-8").read()

raw_entries = re.findall(r'"([^"]{4,80})":\s*\{[^}]*?"location":\s*"([A-Za-z ,.\'-]+)"', content)
school_to_loc = {}
for school, loc in raw_entries:
    loc = loc.strip()
    if loc and ',' in loc:
        parts = [p.strip() for p in loc.split(',', 1)]
        if len(parts) == 2 and len(parts[1].strip()) == 2:
            school_to_loc[school] = (parts[0], parts[1].strip(), loc)

alias_map = {}
for m in re.finditer(r'"([^"]+)":\s*\("([^"]+)",\s*"[^"]*"\)', content):
    alias_map[m.group(1)] = m.group(2)

snap_schools = list(dict.fromkeys(
    r['Team'].strip()
    for r in csv.DictReader(open("output/lane4_snapshot_compatible.csv", encoding="utf-8"))
    if r['Team'].strip()
))

print(f"Snapshot schools: {len(snap_schools)}")

